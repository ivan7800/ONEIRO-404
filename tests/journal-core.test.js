const assert=require('assert');
const core=require('../js/journal-core.js');
const entry=core.normalizeEntry({title:'  Pasillo  ',text:'Puerta roja en un HOTEL',mode:'Liminal',vividness:120,lucidity:65,tags:'puerta, hotel, puerta',places:'Hotel; Pasillo'});
assert.equal(entry.title,'Pasillo');
assert.equal(entry.vividness,100);
assert.equal(entry.lucid,true);
assert.deepEqual(entry.tags,['puerta','hotel']);
assert.deepEqual(entry.places,['Hotel','Pasillo']);
const from=core.fromSession({id:'abc',mode:'Dream',intention:'bosque',recall:{text:'Árbol enorme',vividness:70,lucid:false,savedAt:'2026-10-03T06:00:00Z'}});
assert.equal(from.id,'session-abc');
assert.equal(from.sessionId,'abc');
assert.equal(from.vividness,70);
const list=[entry,from,core.normalizeEntry({title:'Mar',text:'océano',mode:'Dream',vividness:20,lucidity:0,dreamAt:'2026-10-04T00:00:00Z'})];
assert.equal(core.searchEntries(list,{query:'arbol'}).length,1);
assert.equal(core.searchEntries(list,{mode:'Dream'}).length,2);
assert.equal(core.searchEntries(list,{lucid:'yes'}).length,1);
assert.equal(core.searchEntries(list,{minVividness:50}).length,2);
assert.equal(core.searchEntries(list,{sort:'vividness'})[0].vividness,100);
const summary=core.summarize(list);
assert.equal(summary.count,3);
assert.equal(summary.lucidCount,1);
console.log('PASS journal-core:',summary);
